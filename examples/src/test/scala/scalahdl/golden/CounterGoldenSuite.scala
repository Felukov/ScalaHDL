package scalahdl.golden

import java.nio.file.Files
import scala.sys.process._
import scalahdl.examples.Counter
import scalahdl.emit.{Emission, Emitted}

/** R12 / R20 — the `Counter` design's behavioural and file-level contract.
  *
  * What this suite asserts is what an example promises: it emits one file named
  * after its module, the manifest lists it (R20), two emission runs produce
  * identical bytes (R20.1), the R20.2 header names the version and the generator
  * and carries no timestamp, and Verilator `--lint-only` confirms the emitted
  * Verilog is legal. The emitted construction bytes are the emitter's contract
  * and are pinned by the `core` corpus, not here. */
class CounterGoldenSuite extends munit.FunSuite:

  def emitted(): Emitted =
    val m = new Counter
    val design = m.elaborateDesign()
    new Emission().emit(design)

  test("the whole design emits one file named after its module (R20)"):
    val e = emitted()
    assertEquals(e.files.map(_._1), List("Counter.v"),
      "filename must match module name (R20)")

  test("manifest.f lists Counter.v"):
    val e = emitted()
    assertEquals(e.manifest, "Counter.v\n", "manifest lists files in dependency order (R20)")

  test("two emission runs produce identical bytes (R20 reproducibility)"):
    val a = emitted()
    val b = emitted()
    assertEquals(a.files, b.files, "identical input must yield identical output")
    assertEquals(a.manifest, b.manifest)

  test("header has version + generator class + parameters, no timestamp"):
    val header = emitted().files.head._2.linesIterator.take(3).toList
    assertEquals(header, List(
      "// Generated by ScalaHDL 0.1.2",
      "// Generator: scalahdl.examples.Counter",
      "// Parameters: none"
    ))
    assert(!header.exists(_.matches(".*20[0-9][0-9].*")),
      s"header must not contain a timestamp: ${header.mkString("\n")}")

  test("verilator --lint-only passes on emitted Verilog"):
    assume(Seq("sh", "-c", "command -v verilator >/dev/null 2>&1").! == 0,
      "Verilator not on PATH; skipping R20's lint check")
    val e = emitted()
    val dir = Files.createTempDirectory("scalahdl-golden")
    try
      new Emission().writeTo(e, dir.toString)
      val vfile = dir.resolve("Counter.v").toString
      val rc = Seq("verilator", "--lint-only", "-Wall", vfile).!
      assert(rc == 0, s"verilator --lint-only failed (rc=$rc) on $vfile")
    finally
      val _ = Seq("rm", "-rf", dir.toString).!
