package scalahdl.golden

import java.nio.file.Files
import scala.sys.process.*
import scalahdl.core.{Direction, ResetPolarity, Type}
import scalahdl.examples.FlowExample
import scalahdl.emit.{Emission, Emitted}

/** The `FlowExample`'s promise: the port group behaves like SpinalHDL's
  * `val io = new Bundle { ... }`. The module's four data ports are one
  * endpoint named `io`, flattened by R7.1, and the design is an ordinary
  * no-argument top that emits, reproduces, and lints.
  *
  * The emitted bytes are not pinned here: they are the emitter's contract and
  * live in the `core` corpus. What is asserted is the grouping itself — the
  * port list and directions — plus the file-level promises every example
  * makes. */
class FlowExampleSuite extends munit.FunSuite:

  private def design = new FlowExample().elaborateDesign()

  private def emitted(): Emitted = new Emission().emit(design)

  test("the `io` endpoint is one group of ports, flattened by R7.1"):
    assertEquals(design.top.ports.map(p => (p.name, p.direction, p.typeOf)), List(
      ("clk", Direction.In, Type.Clock),
      ("rst", Direction.In, Type.Reset(ResetPolarity.ActiveHigh)),
      ("io_request_valid", Direction.In, Type.Bool),
      ("io_request_payload", Direction.In, Type.UInt(8)),
      ("io_answer_valid", Direction.Out, Type.Bool),
      ("io_answer_payload", Direction.Out, Type.UInt(8))))

  test("the whole design emits one file named after its module"):
    assertEquals(emitted().files.map(_._1), List("FlowExample.v"))
    assertEquals(emitted().manifest, "FlowExample.v\n")

  test("two emission runs produce identical bytes"):
    val a = emitted()
    val b = emitted()
    assertEquals(a.files, b.files)
    assertEquals(a.manifest, b.manifest)

  test("the header names the example, with no timestamp"):
    val header = emitted().files.head._2.linesIterator.take(3).toList
    assertEquals(header, List(
      "// Generated by ScalaHDL 0.1.2",
      "// Generator: scalahdl.examples.FlowExample",
      "// Parameters: none"))
    assert(!header.exists(_.matches(".*20[0-9][0-9].*")),
      s"header must not contain a timestamp: ${header.mkString("\n")}")

  test("verilator --lint-only passes on the emitted Verilog"):
    assume(Seq("sh", "-c", "command -v verilator >/dev/null 2>&1").! == 0,
      "Verilator not on PATH; skipping the lint check")
    val e = emitted()
    val dir = Files.createTempDirectory("scalahdl-flow-example")
    try
      new Emission().writeTo(e, dir.toString)
      val vfile = dir.resolve("FlowExample.v").toString
      val rc = Seq("verilator", "--lint-only", "-Wall", vfile).!
      assert(rc == 0, s"verilator --lint-only failed (rc=$rc) on $vfile")
    finally
      val _ = Seq("rm", "-rf", dir.toString).!
