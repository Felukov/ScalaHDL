package scalahdl.emit

import scalahdl.core.*
import SignalId.*
import scalahdl.clock.{ClockDomain, ResetKind}
import scalahdl.core.ResetPolarity

/** R12 / R9 — Verilog-2001 emitter. Reads the IR (R17) and writes Verilog
  * without mutating it. One block per driver block (R12: one signal, one
  * driver block); nesting depth, branch order, and statement order match the
  * source. No ternary collapse, no reordering, no merging.
  *
  * R12.1 — a driver block that is *one unconditional assignment to the whole
  * signal* emits as a continuous `assign` and its target is a `wire`. Every
  * other combinational block is an `always @(*)`. See `isContinuous`.
  *
  * R20.2 — reproducible header: build-supplied library version, top generator
  * class, and its ordered R16 parameter encodings. No timestamps or runtime
  * identifiers — output is byte-for-byte reproducible.
  *
  * The emitter holds no mutable state derived from the IR; the name lookup is
  * built fresh per module from the immutable `Module`, so the IR is unchanged
  * before and after emission (R17 exit criterion: hash before/after, identical). */
final class VerilogEmitter(version: String, vendor: Option[Vendor] = None):

  /** Emit one module to its file content (R20: filename == module name). */
  def emitModule(m: Module, generation: GenerationInfo): String =
    val names = m.signals.iterator.map(s => s.id -> s.name).toMap
    val ports = m.ports.iterator.map(_.name).toSet
    // Port ids: a signal whose name matches a port name is a port (R10).
    val portIds = m.signals.iterator.filter(s => ports.contains(s.name)).map(_.id).toSet
    val types = m.signals.iterator.map(s => s.id -> s.typeOf).toMap
    val ctx = EmitCtx(names, portIds, types, m.name)
    val sb = new StringBuilder

    // Signals that have a driver block. An output driven by an *always* block
    // must be declared `output reg` in Verilog (a procedural assignment target
    // cannot be a wire, whether the signal is combinational or clocked) — and
    // one driven by a continuous `assign` must not be, which is R12.1's other
    // half and the reason the two sets below are separate.
    val driven = m.drivers.iterator.map(_.signalId).toSet
    // R12.1 — the signals whose driver is a *continuous* assignment. They are
    // nets rather than variables: `assign` may not target a `reg`, and the
    // whole point is that the value holds without an event to carry it.
    val continuous =
      m.drivers.iterator.filter(continuousAssigns(_).isDefined).map(_.signalId).toSet
    val proceduralNames =
      m.signals.iterator.filter(s => driven(s.id) && !continuous(s.id))
        .map(_.name).toSet

    // The emission header. The explicit keys make the contract stable and
    // grep-able; the empty parameter list is represented canonically as `none`.
    val parameters = generation.parameters match
      case Nil => "none"
      case encoded => encoded.mkString(", ")
    sb.append(s"// Generated by ScalaHDL $version\n")
    sb.append(s"// Generator: ${generation.generatorClass}\n")
    sb.append(s"// Parameters: $parameters\n")
    sb.append(s"module ${m.name}(\n")

    // Ports in declaration order (R10). Verilog port names are exactly the
    // val names (R1) — no prefix to strip. An output driven by an always block
    // (combinational or clocked) is `output reg`; an input or undriven output
    // stays a wire.
    //
    // R07.1/R14.1: an aggregate (Bundle/Vec) port expands to one leaf
    // line per leaf, joined by `_` (Vec contributes the numeric index). The
    // `reg` decision is per-port: if the aggregate root is driven, all its
    // leaves are `reg` (the driver block targets the root; every leaf is a
    // procedural assignment target).
    val portLines = m.ports.flatMap { p =>
      val isReg = p.direction == Direction.Out && proceduralNames.contains(p.name)
      val regKw = if isReg then "reg " else ""
      LeafName.leaves(p.name, p.typeOf).map { case (leafName, leafType) =>
        s"  ${p.direction.verilog} $regKw${leafType.verilogRange}$leafName"
      }
    }
    sb.append(portLines.mkString(",\n"))
    sb.append("\n);\n")

    // Internal signal declarations. Ports are declared in the port list, so
    // only non-port signals get a declaration here. R2: anonymous trees never
    // receive a declaration; every signal here is a named val.
    //
    // R14.1: an internal `Bundle` expands to per-leaf scalars; an internal
    // `Vec` expands to a struct-of-arrays — one net array per leaf field
    // (`entries_addr [0:3]`). A scalar stays one `wire`/`reg`.
    val portNames = m.ports.iterator.map(_.name).toSet
    m.signals.filterNot(s => portNames.contains(s.name)).foreach { s =>
      // A signal procedurally assigned in an `always` needs `reg` in
      // Verilog-2001 even when the DSL signal is combinational; one that R12.1
      // emits as a continuous `assign` needs `wire`, because that is what a
      // continuous assignment may target. An undriven signal is a wire too,
      // and reaches the same keyword by the other road.
      val kw =
        if continuous.contains(s.id) then "wire"
        else if s.isReg || driven.contains(s.id) then "reg"
        else "wire"
      s.typeOf match
        case Type.Bundle(_) | Type.Vec(_, _) =>
          // Aggregate: recursively expand to scalar leaves and preserve every
          // Vec dimension as an unpacked array dimension (strict R14).
          LeafName.internalLeaves(s.name, s.typeOf).foreach { leaf =>
            val ranges = leaf.dimensions.map(n => s" [0:${n - 1}]").mkString
            sb.append(s"  $kw ${leaf.scalarType.verilogRange}${leaf.name}$ranges;\n")
          }
        case scalar =>
          // R13.8 — the declaration carries the power-up value, in any
          // domain; `init` is the reset value and lives in the reset branch.
          val powerUp = s.powerUp.map(v => s" = ${emitExpr(v, ctx)}").getOrElse("")
          sb.append(s"  $kw ${scalar.verilogRange}${s.name}$powerUp;\n")
    }

    // R15 — Explicit memories remain first-class until emission. Each uses a
    // packed portable Verilog array plus inference attributes; no primitives.
    m.memories.foreach(mem => sb.append(emitMemory(mem, ctx)))

    // Driver blocks in source (declaration) order — R12, R20.1.
    val byId = m.signals.iterator.map(s => s.id -> s).toMap
    m.drivers.foreach { db =>
      val sig = byId(db.signalId)
      sb.append(emitDriverBlock(db, sig, ctx))
    }

    // Submodule instances — R13.2 / R10. Each instance emits as a Verilog
    // module instantiation with named port connections. Output ports of the
    // child that are connected here need a `wire` declaration; inputs are
    // driven by the connection expression. Clock and reset are auto-connected
    // from the enclosing domain unless the instance names them explicitly.
    m.instances.foreach { inst =>
      sb.append(emitInstance(inst, ctx))
    }

    // R27 — the simulation-only blocks, last, because they are the one part of
    // the file a synthesiser deletes and a reader should be able to stop before
    // them and have read the whole circuit. Every module above this line is the
    // hardware; everything below is what the design claims about it.
    m.checks.foreach(cb => sb.append(emitCheckBlock(cb, m.name, ctx)))

    sb.append("endmodule\n")
    sb.toString
  end emitModule

  /** Compatibility entry point for focused emitter tests and manually-built IR. */
  def emitModule(m: Module, generatorClass: String): String =
    emitModule(m, GenerationInfo(generatorClass, Nil))

  /** R15/R15.1/R15.3 — Emit one portable inference pattern. Element values are
    * packed at the memory boundary, while public aggregate read results retain
    * the normal flattened leaf representation. Ports sharing a clock domain are
    * emitted in one always block so each write has exactly one procedural
    * driver and every read keeps its required register beside the array read. */
  /** R15.3 — which writes one read port's write-first bypass reaches.
    *
    * `WriteFirst` reaches every write on the read's clock: the memory has
    * reads and writes and nothing pairing them, so "this cycle's writes" is
    * all the policy can mean and the bypass carries an address comparison to
    * find the collisions.
    *
    * `WriteFirstPort` reaches the writes on **this read's own port**, which is
    * the writes at its own address — because one physical port of a dual-port
    * RAM is one address with a read and a write on it. That is the only shape
    * a block RAM implements: no vendor's true dual-port memory forwards one
    * port's write into the other port's read, so a bypass that crosses ports
    * cannot infer as the block memory the array is declared to be. */
  private def bypasses(read: MemoryReadPort, write: MemoryWritePort): Boolean =
    read.policy != ReadDuringWrite.WriteFirstPort || write.address == read.address

  private def bypassedWrites(mem: Memory, read: MemoryReadPort): List[MemoryWritePort] =
    mem.writes.filter(w => w.domain.clock == read.domain.clock && bypasses(read, w))

  private def emitMemory(mem: Memory, ctx: EmitCtx): String =
    val sb = new StringBuilder
    val width = mem.elemType.bitWidth
    val range = if width == 1 then "" else s"[${width - 1}:0] "
    // R15.7 — the hint, in the words of the vendor emission names; none
    // without one.
    val hint = vendor.map(v => s"(* ${v.memoryAttribute(mem.kind)} *) ").getOrElse("")
    sb.append(s"  ${hint}reg ${range}${mem.name} [0:${mem.depth - 1}];\n")

    // R15.4 — initial contents load the declared array at time zero. It sits
    // directly under the declaration and outside every `always` block: this is
    // a power-on image, not a reset value, and memories are never reset (R15.1).
    mem.init.foreach { init =>
      val (task, path) = init match
        case MemoryInit.HexFile(p) => ("$readmemh", p)
      sb.append(s"  initial $task(${verilogString(path)}, ${mem.name});\n")
    }

    // Every read has a packed intermediate. Sync intermediates are registers;
    // async intermediates are wires continuously reading the array.
    mem.reads.foreach { read =>
      val resultName = ctx.name(read.result)
      val packedName = s"${resultName}_mem_data"
      val kw = if read.synchronous then "reg" else "wire"
      sb.append(s"  $kw $range$packedName;\n")
      if !read.synchronous then
        val arrayRead = s"${mem.name}[${emitExpr(read.address, ctx)}]"
        val value = read.policy match
          case ReadDuringWrite.WriteFirst | ReadDuringWrite.WriteFirstPort =>
            // R05.5 — a read bypasses every write on *its clock*, whatever
            // reset shape each was recorded under. R15.3's `WriteFirstPort`
            // narrows that to the writes on this read's own port, which is the
            // writes at its own address.
            bypassedWrites(mem, read).foldRight(arrayRead) { (w, fallback) =>
              if read.policy == ReadDuringWrite.WriteFirstPort then
                // Its own port: one address, so the collision test is a
                // tautology and the bypass is the write enable alone.
                w.enable.fold(emitExpr(w.data, ctx))(en =>
                  s"((${emitExpr(en, ctx)}) ? ${emitExpr(w.data, ctx)} : $fallback)")
              else
                val collision = s"(${emitExpr(w.address, ctx)} == ${emitExpr(read.address, ctx)})"
                val enabled = w.enable.fold(collision)(en => s"(${emitExpr(en, ctx)} && $collision)")
                s"($enabled ? ${emitExpr(w.data, ctx)} : $fallback)"
            }
          case _ => arrayRead
        sb.append(s"  assign $packedName = $value;\n")
      sb.append(emitPackedResult(resultName, packedName, mem.elemType))
    }

    // R15.1 — **the block structure follows the kind, because the kind is a
    // claim about the physical thing.**
    //
    // A block memory is ports, so each access gets an `always` block of its
    // own. Inference is template matching rather than reasoning about meaning:
    // a block holding two writes states a *priority* between them — later
    // statement wins — which no physical port has, so the match fails and the
    // whole array falls to registers. Measured on a Cyclone V, one 1 KB array
    // with two addresses each read and written: one block gives 8,208
    // registers and no block memory, one block per access gives none and 8,192
    // bits. Splitting only the reads does not help — still 8,208 — because it
    // is the shared write block that fails to be a port.
    //
    // A register file and a LUT RAM are logic, and their accesses stay in one
    // block. There are no ports to match, and the priority a single block
    // states is the meaning: `Rtc`'s parameter RAM has three writes, and as
    // three blocks they are three drivers on one net, which is a synthesis
    // error rather than a slower design.
    //
    // **The regrouping preserves behaviour where writes are exclusive**, which
    // is what a block memory's ports require anyway — two ports writing one
    // address on one edge is undefined on every vendor's part. Every
    // non-blocking right-hand side is evaluated before any left-hand side
    // updates, so a read never sees a write from its own edge whichever block
    // it sits in, and the read-during-write bypasses below are explicit
    // expressions over the writes on this *clock* rather than over the writes
    // in this block. Grouping by the whole domain record rather than the clock
    // would split ports differing only in reset shape and lose that.
    val perAccess = mem.kind == MemoryKind.BlockRam
    val clocks = (mem.writes.map(_.domain.clock) ++
      mem.reads.filter(_.synchronous).map(_.domain.clock)).distinct
    clocks.foreach { clock =>
      val writes = mem.writes.filter(_.domain.clock == clock)
      val reads = mem.reads.filter(r => r.synchronous && r.domain.clock == clock)
      val statements = List.newBuilder[String]
      reads.foreach { read =>
        val sb = new StringBuilder
        val out = s"${ctx.name(read.result)}_mem_data"
        val addr = emitExpr(read.address, ctx)
        // R15.6 — the read enable stays on the port, so the statement is the
        // inference template `if (enable) q <= mem[a]` and the register holds
        // its value on every other edge. `Undefined` already emits a guard of
        // its own; the enable goes in front of it, because it is the port's
        // and the collision test is the policy's.
        def guarded(condition: Option[String], statement: String): String =
          val terms = read.enable.map(e => s"(${emitExpr(e, ctx)})").toList ++ condition
          if terms.isEmpty then s"    $statement\n"
          else emitIf(terms.mkString(" && "), s"      $statement", Nil, 4, "<=", ctx) + "\n"
        read.policy match
          case ReadDuringWrite.ReadFirst =>
            sb.append(guarded(None, s"$out <= ${mem.name}[$addr];"))
          case ReadDuringWrite.WriteFirst | ReadDuringWrite.WriteFirstPort =>
            val bypassed = writes.filter(bypasses(read, _))
            if bypassed.isEmpty then
              sb.append(guarded(None, s"$out <= ${mem.name}[$addr];"))
            else
              val bypass = bypassed.foldRight(s"${mem.name}[$addr]") { (w, fallback) =>
                if read.policy == ReadDuringWrite.WriteFirstPort then
                  // R15.3 — one physical port is one address, so what remains
                  // of the collision test is the write enable.
                  w.enable.fold(emitExpr(w.data, ctx))(en =>
                    s"((${emitExpr(en, ctx)}) ? ${emitExpr(w.data, ctx)} : $fallback)")
                else
                  val collision = s"(${emitExpr(w.address, ctx)} == $addr)"
                  val enabled = w.enable.fold(collision)(en => s"(${emitExpr(en, ctx)} && $collision)")
                  s"($enabled ? ${emitExpr(w.data, ctx)} : $fallback)"
              }
              sb.append(guarded(None, s"$out <= $bypass;"))
          case ReadDuringWrite.Undefined =>
            if writes.isEmpty then
              sb.append(guarded(None, s"$out <= ${mem.name}[$addr];"))
            else
              val noCollision = writes.map { w =>
                val different = s"(${emitExpr(w.address, ctx)} != $addr)"
                w.enable.fold(different)(en => s"(!${emitExpr(en, ctx)} || $different)")
              }.mkString(" && ")
              sb.append(guarded(Some(noCollision), s"$out <= ${mem.name}[$addr];"))
        statements += sb.toString
      }
      writes.foreach { write =>
        val statement = s"${mem.name}[${emitExpr(write.address, ctx)}] <= ${emitExpr(write.data, ctx)};"
        statements += (write.enable match
          case Some(enable) =>
            emitIf(emitExpr(enable, ctx), s"      $statement", Nil, 4, "<=", ctx) + "\n"
          case None         => s"    $statement\n")
      }
      if perAccess then
        statements.result().foreach { s =>
          sb.append(s"  always @(posedge ${clock.name}) begin\n$s  end\n")
        }
      else
        sb.append(s"  always @(posedge ${clock.name}) begin\n")
        statements.result().foreach(sb.append)
        sb.append("  end\n")
    }
    sb.toString

  /** Connect a packed memory result to the normal scalar/flattened aggregate
    * signal representation. Bundle fields occupy MSBs in declaration order;
    * Vec elements pack descending, matching R07.2. */
  private def emitPackedResult(resultName: String, packedName: String, t: Type): String =
    val sb = new StringBuilder
    def loop(name: String, current: Type, high: Int): Int = current match
      case Type.Bundle(fields) =>
        var h = high
        fields.foreach { case (field, ft) => h = loop(s"${name}_$field", ft, h) }
        h
      case Type.Vec(n, elem) =>
        var h = high
        (0 until n).reverse.foreach(i => h = loop(s"${name}_$i", elem, h))
        h
      case scalar =>
        val low = high - scalar.bitWidth + 1
        val rhs = if scalar.bitWidth == 1 then s"$packedName[$high]" else s"$packedName[$high:$low]"
        sb.append(s"  assign $name = $rhs;\n")
        low - 1
    loop(resultName, t, t.bitWidth - 1)
    sb.toString

  /** Emit a generated or external module instantiation. R18.3 parameters stay
    * ordered and typed until this rendering boundary. */
  private def emitInstance(inst: Instance, ctx: EmitCtx): String =
    val sb = new StringBuilder
    sb.append(s"  ${inst.target}")
    if inst.parameters.nonEmpty then
      sb.append(" #(\n")
      val parameterLines = inst.parameters.map { p =>
        s"    .${p.name}(${emitBlackBoxParam(p.value)})"
      }
      sb.append(parameterLines.mkString(",\n"))
      sb.append("\n  )")
    sb.append(s" ${inst.name}")
    // A port-less instantiation still needs its parentheses: `Child u;` parses
    // as a *variable declaration* of an unknown type, which Verilog accepts
    // syntactically and every downstream tool then rejects with a confusing
    // "can't find typedef" (R09/R23).
    if inst.connections.isEmpty then sb.append("();\n")
    else
      sb.append("(\n")
      val lines = inst.connections.flatMap { case (port, expr) =>
        connectionLines(port, expr, ctx, inst.wholePorts.contains(port))
      }
      sb.append(lines.mkString(",\n"))
      sb.append("\n  );\n")
    sb.toString

  /** R23/R07.1/R18.5 — the connection lines for one connected port. An
    * aggregate port connects *whole* in the source (R23), and Verilog-2001 has
    * no aggregate port to connect it to: the child declared one leaf per field
    * (R07.1) and so did the parent, so the instantiation names leaf against
    * leaf. The exception is an external module's unpacked-array port (R18.5),
    * where the child really does have one port carrying an array. The port side takes R07.1's port-boundary spelling; the parent side
    * goes through the same typed path renderer every other expression uses, so
    * an internal `Vec` stays a net array and a port `Vec` stays per-element
    * (R14.1). A scalar port is one line, exactly as before. */
  private def connectionLines(port: String, expr: Expr, ctx: EmitCtx,
                              whole: Boolean = false): List[String] =
    ctx.typeOfExpr(expr) match
      // R18.5 — an external module's unpacked-array port. It is one port
      // carrying an array, so it takes one connection naming the parent's net
      // array; the parent side is an internal `Vec`, which R14.1 already emits
      // as exactly that. A leaf-by-leaf connection would name ports the
      // external module does not have, and a packed vector is a type error in
      // every tool, so this is the only spelling that exists.
      case Type.Vec(_, _) if whole =>
        val (rootId, rootSteps) = flattenExprPath(expr)
        if ctx.isPort(rootId) then throw EmitterError(
          s"an unpacked-array port cannot be connected to `${ctx.name(rootId)}`, which is a " +
          "port of this module and is therefore one net per element — " +
          "connect an internal Vec signal")
        List(s"    .$port(${renderPath(rootId, rootSteps, ctx)})")
      case aggregate @ (Type.Bundle(_) | Type.Vec(_, _)) =>
        val (rootId, rootSteps) = flattenExprPath(expr)
        leafPaths(aggregate).map { case (suffix, leafSteps) =>
          s"    .$port$suffix(${renderPath(rootId, rootSteps ++ leafSteps, ctx)})"
        }
      case _ => List(s"    .$port(${emitExpr(expr, ctx)})")

  private def emitBlackBoxParam(value: BlackBoxParamValue): String = value match
    case BlackBoxParamValue.Integer(v) => v.toString
    case BlackBoxParamValue.Real(v) =>
      val rendered = v.toString
      if rendered.contains('.') || rendered.contains('e') || rendered.contains('E') then rendered
      else rendered + ".0"
    case BlackBoxParamValue.Str(v) => verilogString(v)

  /** One Verilog string literal, with the two characters a literal cannot carry
    * raw escaped. Shared by R18 blackbox parameters and R15.4 image paths. */
  private def verilogString(value: String): String =
    "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

  /** R12.1 — the assignment a driver block reduces to when it is *one
    * unconditional assignment to the whole signal*, and is therefore a
    * **continuous** assignment rather than a procedural one. `None` for every
    * other block.
    *
    * R12's promise is that the emitted Verilog reads like the source that
    * produced it, and its worked example argues against collapsing a `when`
    * nest into a ternary for exactly that reason. **This is the opposite
    * case.** The source wrote one assignment and no condition; `assign x =
    * expr;` is that, and `always @(*) begin x = expr; end` is three lines of
    * scaffolding around it. Nothing is flattened, reordered or merged — the
    * correspondence R12 exists to keep is closer here, not looser.
    *
    * **And the procedural form is wrong when the expression reads nothing.**
    * `always @(*) begin x = 11'd1300; end` has an empty sensitivity list:
    * IEEE 1800 §9.4.2.2 builds the list from the variables the block reads, a
    * block with no list has no event to trigger it, and the signal keeps its
    * initial value — `x` — for the whole simulation. Verilator says so
    * (`ALWNEVER`, and `UNDRIVEN` on the target), and a design can arrive there
    * without anybody writing anything odd: deleting a `Mux` on a strap in a
    * design turned a legitimate `Wire` into an illegal one, with
    * nothing about the edit looking wrong. A continuous assignment holds from
    * time zero whatever it reads, so the failure is not merely detected here,
    * it is **unrepresentable**.
    *
    * The condition is deliberately narrow, and the narrowness is the argument:
    *
    *   - **combinational only.** A clocked block is an edge and a reset branch
    *     (R13); there is no continuous form of it.
    *   - **unconditional assignments and nothing else.** A `when` is a
    *     condition and a `switch` is a partition, and both are procedural by
    *     nature. Only a block with nothing to sequence qualifies.
    *   - **a whole leaf each, and each leaf once.** A write to a *part* —
    *     `count(7, 0) := d` (R6.7) — would leave the rest of the net undriven
    *     rather than holding, which is a different circuit; and a leaf written
    *     twice is a sequence, where two continuous assignments would be two
    *     drivers. Such a block stays procedural.
    *
    * **An aggregate qualifies, and that is not a detail.** R07.1 expands it to
    * one line per leaf either way, so a driver that assigns several leaves of
    * one bundle — an interface payload, every time — is the same case as a
    * scalar's single assignment. Treating it otherwise emits a block that
    * reads nothing and therefore never runs. */
  private def continuousAssigns(db: DriverBlock): Option[List[Stmt.Assign]] =
    ContinuousDriver.assigns(db)

  /** Emit one driver block as an `always` (R12). The sensitivity list and
    * reset branch follow mechanically from the domain's kind + polarity (R13):
    *
    *   - Sync  + ActiveHigh → `posedge clk`           / `if (rst)`
    *   - Sync  + ActiveLow  → `posedge clk`           / `if (!rst_n)`
    *   - Async + ActiveHigh → `posedge clk or posedge rst` / `if (rst)`
    *   - Async + ActiveLow  → `posedge clk or negedge rst_n` / `if (!rst_n)`
    *   - None               → `posedge clk` / no reset branch
    *
    * The `init` is the *value*; the *shape* is the domain's (R13). A register
    * with no `init` in a reset domain has no value to reset to and so is not
    * reset: it emits `posedge clk` alone, dropping the async edge along with
    * the branch, because an edge with no branch would sample `d` on the reset
    * rather than hold. */
  private def emitDriverBlock(db: DriverBlock, sig: Signal, ctx: EmitCtx): String =
    val sb = new StringBuilder
    val assign = if db.clocked then "<=" else "="
    if continuousAssigns(db).isDefined then
      // R12.1 — unconditional assignments to whole leaves are continuous
      // assignments. One line per leaf, which for a scalar is one.
      val lines = continuousAssigns(db).get
        .flatMap(a => assignLines(a.target, a.expr, "=", ctx))
      sb.append(lines.map("  assign " + _).mkString("\n"))
      sb.append("\n")
    else if !db.clocked then
      // combinational: always @(*) with blocking =
      sb.append("  always @(*) begin\n")
      sb.append(emitStmts(db.stmts, indent = 4, assign, ctx))
      sb.append("\n  end\n")
    else
      // clocked: the sensitivity list and reset condition come from the domain
      val clk = db.domain.clkName
      db.domain.resetKind match
        case ResetKind.None =>
          sb.append(s"  always @(posedge $clk) begin\n")
          sb.append(emitStmts(db.stmts, indent = 4, assign, ctx))
          sb.append("\n  end\n")
        case kind =>
          // A register with a reset signal but no `init` has no reset *value*,
          // and R13 says it is therefore not reset at all — so the reset leaves
          // the sensitivity list along with the branch. An async edge with no
          // branch to answer it would clock `d` in on the reset instead of
          // holding, which is the opposite of what "not reset" means.
          //
          // The same fall-through covers a reset kind that names no reset
          // signal: nothing to be sensitive to, nothing to branch on.
          (db.domain.rstName, sig.init) match
            case (Some(rst), Some(_)) =>
              val edge = kind match
                case ResetKind.Async =>
                  db.domain.polarity match
                    case ResetPolarity.ActiveHigh => s" or posedge $rst"
                    case ResetPolarity.ActiveLow  => s" or negedge $rst"
                case _ => ""
              val cond = db.domain.polarity match
                case ResetPolarity.ActiveHigh => rst
                case ResetPolarity.ActiveLow  => s"!$rst"
              // The reset is the first link of the chain, so a body that is
              // one `when` continues it as `end else if` (R12.2).
              sb.append(s"  always @(posedge $clk$edge) begin\n")
              sb.append(emitIf(cond, s"      ${sig.name} <= ${emitInit(sig, ctx)};",
                               db.stmts, indent = 4, assign, ctx))
              sb.append("\n  end\n")
            case _ =>
              sb.append(s"  always @(posedge $clk) begin\n")
              sb.append(emitStmts(db.stmts, indent = 4, assign, ctx))
              sb.append("\n  end\n")
    sb.toString

  /** R27 — Emit one check block: an `always` on the domain's clock, wrapped in
    * the pragma that keeps it out of every board.
    *
    * `// synthesis translate_off` is a *comment*, which is what makes it the
    * right guard: Vivado, Quartus and Yosys all honour it and no simulator has
    * to be told anything, because a simulator reads a comment as a comment. An
    * `` `ifdef `` would need every simulation flow to define the macro, and one
    * forgotten flag is a design whose checks are silently absent.
    *
    * **The reset guard is the domain's** (R13). A check is a claim about a
    * running design, so it is not evaluated on an edge taken while reset is
    * asserted — which is what a SystemVerilog concurrent assertion spells
    * `disable iff (reset)`. A domain with no reset gets no guard, because there
    * is nothing to be out of.
    *
    * There is no continuous form and no combinational form: an immediate check
    * needs a moment to be checked at, and an edge is the one moment every
    * signal in the module is settled. */
  private def emitCheckBlock(cb: CheckBlock, moduleName: String, ctx: EmitCtx): String =
    val sb = new StringBuilder
    val clk = cb.domain.clkName
    // The check reads flop outputs at the edge, before this cycle's non-blocking
    // updates land — the same values a concurrent assertion samples in its
    // preponed region. That equivalence holds because the block assigns
    // nothing, so nothing here can be read after having been updated.
    val _ = moduleName
    val guard = (cb.domain.rstName, cb.domain.resetKind) match
      case (Some(_), ResetKind.None) => None
      case (Some(rst), _) => Some(cb.domain.polarity match
        case ResetPolarity.ActiveHigh => s"!$rst"
        case ResetPolarity.ActiveLow  => rst)
      case (None, _) => None
    sb.append("  // synthesis translate_off\n")
    sb.append(s"  always @(posedge $clk) begin\n")
    guard match
      case Some(cond) =>
        sb.append(emitIf(cond, emitStmts(cb.stmts, indent = 6, "=", ctx), Nil,
                         indent = 4, "=", ctx))
        sb.append("\n")
      case None =>
        sb.append(emitStmts(cb.stmts, indent = 4, "=", ctx))
        sb.append("\n")
    sb.append("  end\n")
    sb.append("  // synthesis translate_on\n")
    sb.toString

  /** Emit the reset value for a register, or 0 if none (R13: a register with
    * no `init` in a reset domain is simply not reset — this is only reached
    * when `init` is defined). */
  private def emitInit(sig: Signal, ctx: EmitCtx): String =
    sig.init match
      case Some(e) => emitExpr(e, ctx)
      case None    => literalZero(sig.typeOf)

  private def literalZero(t: Type): String = t match
    case Type.Bool    => "1'b0"
    case Type.UInt(w) => s"${w}'d0"
    case Type.SInt(w) => s"${w}'sd0"
    case Type.Bits(w) => s"${w}'d0"
    case Type.GrayCode(w) => s"${w}'d0"
    case Type.Clock    => "1'b0"
    case Type.Reset(_) => "1'b0"
    case Type.Bundle(fields) =>
      // R07.2 packing: first field in MSBs. Concatenate per-leaf zeros in
      // declaration order.
      val parts = fields.map { case (_, ft) => literalZero(ft) }
      "{" + parts.mkString(", ") + "}"
    case Type.Vec(n, elem) =>
      // R07.2: Vec packs descending (n-1 high). Concatenate n zeros.
      "{" + List.fill(n)(literalZero(elem)).mkString(", ") + "}"

  /** Emit a statement list, one statement after another at `indent` (R12:
    * order and nesting preserved exactly). Each statement carries its own
    * pad. */
  private def emitStmts(stmts: List[Stmt], indent: Int, assign: String,
                        ctx: EmitCtx): String =
    stmts.map(emitStmt(_, indent, assign, ctx)).mkString("\n")

  /** R12.2 — a `begin`/`end` block around `body`, which is already padded to
    * the block's inner column; `end` closes at `indent`, the column of the
    * statement the block belongs to. An empty body is an empty block. */
  private def block(body: String, indent: Int): String =
    val inner = if body.isEmpty then "" else body + "\n"
    s"begin\n$inner${" " * indent}end"

  /** R12.2 — an `if` whose every branch is a `begin`/`end` block.
    *
    * Closing every branch is what makes the text mean the source's nesting
    * without a case analysis: an `else` follows an `end` and so binds to that
    * block's `if`, where Verilog's dangling-else rule would otherwise bind it
    * to the *nearest* unmatched `if`, and a statement that becomes several in
    * Verilog — a whole aggregate, one assignment per leaf — stays inside its
    * branch.
    *
    * An `else` whose whole body is one conditional is that conditional's
    * link in the chain, written `end else if (…) begin` at the chain's
    * column rather than a level deeper. In Verilog `else if` *is* that
    * nesting, so the flat text states the same structure, and a chain reads
    * as the priority list it is. */
  private def emitIf(cond: String, thenBody: String, elseStmts: List[Stmt],
                     indent: Int, assign: String, ctx: EmitCtx): String =
    def chain(stmts: List[Stmt]): String = stmts match
      case Nil => ""
      case Stmt.When(c, t, e, _) :: Nil =>
        s" else if (${emitExpr(c, ctx)}) " +
          block(emitStmts(t, indent + 2, assign, ctx), indent) + chain(e)
      case _ =>
        " else " + block(emitStmts(stmts, indent + 2, assign, ctx), indent)
    s"${" " * indent}if ($cond) " + block(thenBody, indent) + chain(elseStmts)

  /** A `case` arm, after its label. One statement stays on the label's line
    * and its continuation lines — an `if`'s `end`, a nested `endcase` — close
    * at the arm's column, `indent`; several statements are a block. An arm
    * with nothing in it is the empty statement. */
  private def emitArm(stmts: List[Stmt], indent: Int, assign: String,
                      ctx: EmitCtx): String = stmts match
    case Nil => ";"
    case s :: Nil if !emitsSeveral(s, ctx) =>
      emitStmt(s, indent, assign, ctx).drop(indent)
    case _ => block(emitStmts(stmts, indent + 2, assign, ctx), indent)

  /** Whether a statement emits as more than one Verilog statement. A
    * whole-aggregate assignment does: it stays one statement in the IR (R17
    * preserves the aggregate) and becomes one per leaf in Verilog-2001, which
    * has no aggregate to assign (R07.1). On a `case` arm's line that
    * difference decides `begin`/`end` — written bare, only the first leaf
    * would belong to the arm and the rest would be a syntax error. */
  private def emitsSeveral(s: Stmt, ctx: EmitCtx): Boolean = s match
    case Stmt.Assign(target, _, _, _) =>
      val (id, steps) = flattenLhs(target)
      typeAt(id, steps, ctx) match
        case aggregate @ (Type.Bundle(_) | Type.Vec(_, _)) =>
          leafPaths(aggregate).sizeCompare(1) > 0
        case _ => false
    case _ => false

  private def emitStmt(s: Stmt, indent: Int, assign: String, ctx: EmitCtx): String =
    val pad = " " * indent
    s match
      case Stmt.Assign(target, expr, _, _) =>
        // The driver block fixes the assignment kind (R12); use `assign`.
        assignLines(target, expr, assign, ctx).map(pad + _).mkString("\n")
      case Stmt.Check(_, cond, message, _) =>
        // R27 — Verilog-2001 has neither `assert` nor `$error` (R9), so a check
        // is the `if` that states it plus the two tasks 1364 does have. `$stop`
        // rather than report-and-continue: a testbench that prints PASS after
        // an invariant broke is the silent failure this exists to prevent, and
        // `$stop` ends the run with a non-zero status for the script above it.
        //
        // The module name is in the text because the check is inside the
        // module, and a hierarchy of the same component emits the same line in
        // every copy; `%0t` is what says which of them fired and when.
        val text = verilogString(s"[%0t] ${ctx.moduleName}: $message")
        val inner = " " * (indent + 2)
        emitIf(s"!(${emitExpr(cond, ctx)})",
               s"$inner$$display($text, $$time);\n$inner$$stop;", Nil, indent, assign, ctx)
      case Stmt.When(cond, thenStmts, elseStmts, _) =>
        emitIf(emitExpr(cond, ctx), emitStmts(thenStmts, indent + 2, assign, ctx),
               elseStmts, indent, assign, ctx)
      case Stmt.Switch(skind, selector, cases, defaults, _) =>
        // R22 — one native `case` per switch: one item per IR alternative, in
        // elaboration order, with comma-separated labels for aliases and
        // `default` only when the source had one. No sorting, no merging of
        // equal bodies, no conversion to an `if` chain (R12/R20.1).
        //
        // R22.1 — the alternative list the emitter reads is *this signal's*
        // projection of a switch the source may have shared between a dozen
        // signals (R12: one signal, one driver block), so an alternative that
        // writes nothing here is structure the projection carried in, not a
        // statement the source wrote. It is dropped rather than printed as
        // `3'd0: ;`, which on an eight-state FSM buries the one arm that
        // assigns under seven that do not. The IR keeps every arm — R11 reads
        // it to decide whether a combinational target is left uncovered, and
        // that verdict must not depend on emission.
        //
        // Dropping arms would narrow the case's covered value space, so a
        // `default: ;` goes back in its place: the pruned arms did nothing and
        // the default does nothing, which is the same hardware, and the case
        // still reads — and lints (verilator `CASEINCOMPLETE`) — as fully
        // specified rather than as a partial one whose gaps are an oversight.
        //
        // Pruning is off entirely when this projection's `default` assigns
        // something. There an empty arm is not silence but *shadowing*: it is
        // what keeps its values out of the default's statements, and dropping
        // it would route them straight into assignments they must not run.
        val defaultAssigns = defaults.exists(_.nonEmpty)
        val items = if defaultAssigns then cases else cases.filter(_.stmts.nonEmpty)
        val pruned = items.sizeCompare(cases) != 0
        val b = new StringBuilder()
        val itemPad = " " * (indent + 2)
        // R26.1 — a `parallelCase` carries `parallel_case` into the Verilog.
        //
        // R26 proves at elaboration that at most one arm can hold: every arm
        // is a cube over one selector, and an overlapping pair is an error
        // naming both and a witness value. R26 originally drew from that the
        // conclusion that the attribute was redundant — "a proof that has been
        // checked does not need to be asserted as well". That is true of a
        // reader and false of a synthesiser, which has no access to the proof
        // and must therefore read Verilog's `case` the only way the language
        // defines it: in order. A 267-arm cover then synthesises as a 267-deep
        // priority chain, ~146 LUT levels of it, and the measurement that
        // found this put a 68000's instruction decoder at 92 ns of a 98 ns
        // critical path — 10.18 MHz where the same design with the attribute
        // makes 33.23 MHz on 15% fewer ALMs.
        //
        // So the attribute is emitted, and what makes that sound is exactly
        // R26's refusal to accept an arm it cannot decide: a design the
        // attribute would miscompile cannot elaborate. `priorityCase` claims
        // nothing and gets nothing.
        val parallel = if skind == SelectKind.OneHot then " // synopsys parallel_case" else ""
        b.append(s"${pad}case (${emitExpr(selector, ctx)})$parallel\n")
        items.foreach { alternative =>
          val labels = alternative.values.map(emitExpr(_, ctx)).mkString(", ")
          b.append(s"$itemPad$labels: ")
          b.append(emitArm(alternative.stmts, indent + 2, assign, ctx))
          b.append("\n")
        }
        defaults match
          case Some(defaultStmts) =>
            b.append(s"${itemPad}default: ")
            b.append(emitArm(defaultStmts, indent + 2, assign, ctx))
            b.append("\n")
          case None if pruned =>
            // The source had no default; this one stands for the arms just
            // dropped and says exactly what they said.
            b.append(s"${itemPad}default: ;\n")
          case None => ()
        b.append(s"${pad}endcase")
        b.toString
      case Stmt.MemWrite(id, _, _, _) =>
        // A memory's write ports are emitted with the memory declaration, so a
        // statement naming a write target has no statement form of its own.
        s"$pad/* mem write ${ctx.name(id)} */"

  /** The Verilog statements one IR assignment becomes. A scalar target is one
    * statement. A whole-aggregate target is one per leaf: `resp := u.resp` is a
    * single R17 statement over a preserved aggregate, and Verilog-2001 has no
    * aggregate to assign, so it lands as `resp_ack = u_resp_ack;` and
    * `resp_data = u_resp_data;` — the same leaves the source could have written
    * by hand, in declaration order (R07.1).
    *
    * Both sides walk the *same* leaf paths, which is what makes the pairing
    * field-by-field rather than positional; each side is then rendered by the
    * shared path renderer, so it takes its own port-versus-internal spelling
    * (R14.1). */
  private def assignLines(target: Lhs, expr: Expr, assign: String,
                          ctx: EmitCtx): List[String] =
    val (lhsId, lhsSteps) = flattenLhs(target)
    typeAt(lhsId, lhsSteps, ctx) match
      case aggregate @ (Type.Bundle(_) | Type.Vec(_, _)) =>
        val (rhsId, rhsSteps) = flattenExprPath(expr)
        leafPaths(aggregate).map { case (_, leafSteps) =>
          s"${renderPath(lhsId, lhsSteps ++ leafSteps, ctx)} $assign " +
            s"${renderPath(rhsId, rhsSteps ++ leafSteps, ctx)};"
        }
      case _ => List(s"${emitLhs(target, ctx)} $assign ${emitRhs(expr, ctx)};")

  /** Every scalar leaf of a type, as the R07.1 name suffix that reaches it
    * paired with the IR path that selects it. A scalar is its own single leaf
    * with an empty suffix and an empty path, so a caller needs no special case
    * for the non-aggregate shape. */
  private def leafPaths(t: Type): List[(String, List[PathStep])] = t match
    case Type.Bundle(fields) =>
      fields.flatMap { case (name, fieldType) =>
        leafPaths(fieldType).map { case (suffix, steps) =>
          (s"_$name$suffix", PathStep.Field(name) :: steps)
        }
      }
    case Type.Vec(n, elem) =>
      (0 until n).toList.flatMap { i =>
        leafPaths(elem).map { case (suffix, steps) =>
          (s"_$i$suffix", PathStep.Index(Expr.uint(BigInt(i), 32)) :: steps)
        }
      }
    case _ => List(("", Nil))

  /** The type at an aggregate path, answered by the shared typer (R21.6) so
    * field and index rules are stated once rather than re-derived here. */
  private def typeAt(id: SignalId, steps: List[PathStep], ctx: EmitCtx): Type =
    ctx.typeOfExpr(steps.foldLeft[Expr](Expr.Ref(id)) { (base, step) =>
      step match
        case PathStep.Field(name)  => Expr.Field(base, name)
        case PathStep.Index(idx)   => Expr.Index(base, idx)
        case PathStep.Slice(hi, lo) => Expr.Slice(base, hi, lo)
        case PathStep.VarSlice(lo, w) => Expr.VarSlice(base, lo, w)
    })

  /** Emit an assignment target through the same recursive typed path renderer
    * used for RHS expressions. Every index is interpreted against the Type at
    * that path position, not merely against the root Type. */
  private def emitLhs(lhs: Lhs, ctx: EmitCtx): String =
    val (id, steps) = flattenLhs(lhs)
    renderPath(id, steps, ctx)

  /** Emit the right-hand side of an assignment. Identical to `emitExpr` but
    * for R6.2's one exception, which only exists in this position: a narrowing
    * `resize` of an *anonymous* operand emits no selection at all, because
    * Verilog truncates natively at the target. That is what keeps
    * `x := (a + b).resize(8)` legal with no intermediate `val` (R21.4).
    *
    * A bit-addressable operand keeps its explicit `[w-1:0]` here rather than
    * riding on the same native truncation: the selection is what the source
    * says, it reads the same in this position as in every other, and it leaves
    * no implicit width change in the output. */
  private def emitRhs(e: Expr, ctx: EmitCtx): String = e match
    case Expr.Resize(to, inner)
        if to < ctx.widthOfExpr(inner) && !ExprType.isBitAddressable(inner) =>
      emitExpr(inner, ctx)
    case other => emitExpr(other, ctx)

  /** R25 — render one expression exactly as this backend would emit it, for a
    * report rather than for a file. The FSM report labels its edges with the
    * guard the `goto` was written under, and rendering it here rather than in
    * a printer of its own is what keeps an edge label and the `if` it became
    * readable as the same expression. */
  private[emit] def renderExpr(e: Expr, m: Module): String =
    val names = m.signals.iterator.map(s => s.id -> s.name).toMap
    val ports = m.ports.iterator.map(_.name).toSet
    val portIds = m.signals.iterator.filter(s => ports.contains(s.name)).map(_.id).toSet
    val types = m.signals.iterator.map(s => s.id -> s.typeOf).toMap
    emitExpr(e, EmitCtx(names, portIds, types))

  /** Emit an expression tree (R2: anonymous, inlined at use). */
  private def emitExpr(e: Expr, ctx: EmitCtx): String = e match
    case Expr.Ref(id)         => ctx.name(id)
    case Expr.Lit(v, wOpt, kind) =>
      emitLit(v, wOpt.getOrElse(1), kind.contains(LitKind.Signed))
    case Expr.UnOp(op, a)      => s"($op${emitExpr(a, ctx)})"
    case Expr.BinOp(op, a, b)  => emitBinOp(op, a, b, ctx)
    case Expr.Mux(sel, whenTrue, whenFalse) =>
      s"(${emitExpr(sel, ctx)} ? ${emitExpr(whenTrue, ctx)} : ${emitExpr(whenFalse, ctx)})"
    case Expr.Slice(base, hi, lo) => emitSelect(base, hi, lo, ctx)
    case Expr.VarSlice(base, lo, w) =>
      // R34 — Verilog's indexed part-select, `base[lo +: w]`.
      s"${emitExpr(base, ctx)}[${emitIndex(lo, ctx)} +: $w]"
    case path @ Expr.Index(_, _) =>
      val (id, steps) = flattenExprPath(path)
      renderPath(id, steps, ctx)
    case path @ Expr.Field(_, _) =>
      val (id, steps) = flattenExprPath(path)
      renderPath(id, steps, ctx)
    case Expr.Cat(parts)        => "{" + parts.map(emitExpr(_, ctx)).mkString(", ") + "}"
    case Expr.Repeat(n, inner)  => s"{$n{${emitExpr(inner, ctx)}}}"
    case Expr.Resize(to, inner) => emitResize(to, inner, ctx)
    case Expr.TypeCast(_, inner) => emitExpr(inner, ctx)
    case Expr.Cdc(CdcPrimitive.Unsafe(justification), inner, _) =>
      s"/* ASYNC_REG: $justification */ ${emitExpr(inner, ctx)}"
    case Expr.Cdc(_, inner, _) => emitExpr(inner, ctx)

  /** R12/R21.7 — a sized Verilog constant. A negative signed literal puts the
    * sign *outside* the sized constant: `-32'sd1`, never `32'sd-1`, which is
    * not Verilog at all (Verilator 5.050: "Number is missing value digits"). */
  private def emitLit(v: BigInt, w: Int, signed: Boolean): String =
    if signed then (if v < 0 then s"-$w'sd${-v}" else s"$w'sd$v")
    else if w == 1 then s"1'b$v"
    else s"$w'd$v"

  /** R21.6 — signedness is applied per operation. `SInt` is emitted as an
    * ordinary Verilog vector with no `signed` declaration, so every signed
    * operation wraps its own operands in `$signed` and every unsigned one
    * wraps nothing. Two Verilog hazards become structurally unreachable: an
    * expression cannot be contaminated by a sibling's declared signedness,
    * and (with R6's width agreement, plus the explicit widening in `*`) no
    * operand is sized by its context. */
  private def emitBinOp(op: String, a: Expr, b: Expr, ctx: EmitCtx): String =
    import ExprType.Op
    if Op.isMultiply(op) then emitMultiply(a, b, ctx)
    else if Op.isArithmeticShift(op) then
      // `>>>` is legal on SInt only, so the operand is always signed; the
      // amount is unsigned and stays bare.
      //
      // The result is wrapped too, and that wrapper is not redundant: Verilog
      // evaluates an expression unsigned in its entirety if *any* operand of
      // it is unsigned, and that decision propagates down into the operands.
      // A bare `($signed(a) >>> n)` sitting in `... + b` with an unsigned `b`
      // therefore shifts a value Verilog has just decided is unsigned, and
      // `>>>` on an unsigned operand is a logical shift — the operation
      // silently becomes the one R21.1 exists to distinguish it from. The
      // operand of `$signed` is self-determined, so the outer wrapper is the
      // boundary the enclosing context cannot reach through.
      //
      // `>>>` is the only operation in the surface that needs this. Every
      // other signed operation is bit-pattern-identical to its unsigned
      // counterpart at the same width — two's-complement `+`, `-`, `<<`, and
      // (because `*` widens both operands to `w1 + w2` first) `*` included —
      // and a comparison's operands form their own signedness context. R12
      // prefers the plainest rendering that is correct, so nothing else is
      // wrapped.
      s"$$signed((${signedOperand(a, ctx)} $op ${emitExpr(b, ctx)}))"
    else if Op.isOrdering(op) && ctx.isSigned(a) then
      // Both operands, always: Verilog evaluates a mixed expression unsigned
      // in its entirety, so dropping one wrapper silently makes an `SLT` an
      // `SLTU`.
      s"(${signedOperand(a, ctx)} $op ${signedOperand(b, ctx)})"
    else s"(${emitExpr(a, ctx)} $op ${emitExpr(b, ctx)})"

  private def signedOperand(e: Expr, ctx: EmitCtx): String =
    s"$$signed(${emitExpr(e, ctx)})"

  /** R21.3/R21.6 — the full `w1 + w2` product. Both operands are widened to
    * the result width *before* multiplying, so the product is self-determined
    * rather than sized by its context — the one place R6's width agreement
    * does not already guarantee that. */
  private def emitMultiply(a: Expr, b: Expr, ctx: EmitCtx): String =
    val aw = ctx.widthOfExpr(a)
    val bw = ctx.widthOfExpr(b)
    val signed = ctx.isSigned(a)
    val aWide = emitExtend(a, aw + bw, signed, ctx)
    val bWide = emitExtend(b, aw + bw, signed, ctx)
    if signed then s"($$signed($aWide) * $$signed($bWide))"
    else s"($aWide * $bWide)"

  /** R21.4 — `resize`: width-changing, kind-preserving. Widening a `UInt` or
    * `Bits` fills with zeros, widening an `SInt` replicates its sign bit, and
    * narrowing keeps the low `w` bits. Resizing to the operand's own width is
    * the identity and emits nothing. */
  private def emitResize(to: Int, inner: Expr, ctx: EmitCtx): String =
    val w = ctx.widthOfExpr(inner)
    if to == w then emitExpr(inner, ctx)
    else if to > w then emitExtend(inner, to, ctx.isSigned(inner), ctx)
    else emitSelect(inner, to - 1, 0, ctx)

  /** Widen an operand to `to` bits: `{{k{1'b0}}, a}` unsigned,
    * `{{k{a[w-1]}}, a}` signed. Shared by `resize` and by `*`'s operand
    * widening so the two can never disagree. */
  private def emitExtend(e: Expr, to: Int, signed: Boolean, ctx: EmitCtx): String =
    val w = ctx.widthOfExpr(e)
    val k = to - w
    if k <= 0 then emitExpr(e, ctx)
    else
      val fill = if signed then emitMsb(e, ctx) else "1'b0"
      s"{{$k{$fill}}, ${emitExpr(e, ctx)}}"

  /** The sign bit of an operand. A 1-bit value is its own sign bit — and a
    * Verilog scalar net cannot be bit-selected at all, so this case must not
    * emit `a[0]`. */
  private def emitMsb(e: Expr, ctx: EmitCtx): String =
    val w = ctx.widthOfExpr(e)
    if w == 1 then emitExpr(e, ctx) else emitSelect(e, w - 1, w - 1, ctx)

  /** Emit a bit-selection of a bit-addressable operand (R6.2): a named signal,
    * a bundle field or vec element of one, or a slice of either. `WidthPhase`
    * rejects anything else before emission; the throw here is the last line of
    * defence, not the user-facing error.
    *
    * Every bit-selection goes through here — a written `sig(hi, lo)` as much as
    * the one R21.4's sign extension builds — so that one selection has one
    * spelling (R12). That is what makes the `hi == lo` collapse below hold
    * everywhere: a one-bit window is a bit-select, `opcode[10]`, never the
    * degenerate part-select `opcode[10:10]`, matching how `emitIndex` already
    * renders `opcode(10)`. The two are the same 1-bit unsigned value in
    * Verilog-2001; the emitter has to pick one, and picks the one a reader of
    * the source would have written. */
  private def emitSelect(e: Expr, hi: Int, lo: Int, ctx: EmitCtx): String = e match
    case Expr.Slice(base, _, sliceLo) =>
      // Verilog has no part-select of a part-select; compose the window into
      // one absolute selection on the underlying signal instead.
      emitSelect(base, sliceLo + hi, sliceLo + lo, ctx)
    case Expr.TypeCast(_, inner) => emitSelect(inner, hi, lo, ctx)   // width-preserving
    case Expr.Cdc(_, inner, _)   => emitSelect(inner, hi, lo, ctx)
    case Expr.Ref(_) | Expr.Field(_, _) | Expr.Index(_, _) =>
      val base = emitExpr(e, ctx)
      if hi == lo then s"$base[$hi]" else s"$base[$hi:$lo]"
    case other =>
      throw EmitterError(
        "bit-selection requires a named signal; an anonymous expression " +
        s"reached emission: $other")

  private enum PathStep:
    case Field(name: String)
    case Index(idx: Expr)
    /** R6.7 — a constant window, and always the last step of a path. */
    case Slice(hi: Int, lo: Int)
    /** R34 — a window of a constant width at a runtime offset. */
    case VarSlice(lo: Expr, width: Int)

  private def flattenExprPath(e: Expr): (SignalId, List[PathStep]) = e match
    case Expr.Ref(id)          => (id, Nil)
    case Expr.Field(base, n)   =>
      val (id, steps) = flattenExprPath(base)
      (id, steps :+ PathStep.Field(n))
    case Expr.Index(base, idx) =>
      val (id, steps) = flattenExprPath(base)
      (id, steps :+ PathStep.Index(idx))
    case Expr.VarSlice(base, lo, w) =>
      val (id, steps) = flattenExprPath(base)
      (id, steps :+ PathStep.VarSlice(lo, w))
    case _ => throw EmitterError("aggregate path must bottom out at a named signal")

  private def flattenLhs(lhs: Lhs): (SignalId, List[PathStep]) = lhs match
    case Lhs.Sig(id)          => (id, Nil)
    case Lhs.Field(base, n)   =>
      val (id, steps) = flattenLhs(base)
      (id, steps :+ PathStep.Field(n))
    case Lhs.Index(base, idx) =>
      val (id, steps) = flattenLhs(base)
      (id, steps :+ PathStep.Index(idx))
    case Lhs.Slice(base, hi, lo) =>
      val (id, steps) = flattenLhs(base)
      (id, steps :+ PathStep.Slice(hi, lo))
    case Lhs.VarSlice(base, lo, w) =>
      val (id, steps) = flattenLhs(base)
      (id, steps :+ PathStep.VarSlice(lo, w))

  /** Render a typed aggregate path. At ports each Vec index is part of the
    * flattened leaf name and therefore must be constant. Internally each Vec
    * index is an unpacked-array suffix, preserving arbitrary nesting. */
  private def renderPath(id: SignalId, steps: List[PathStep], ctx: EmitCtx): String =
    var currentType = ctx.typeOf(id)
    var name = ctx.name(id)
    val arrayIndices = scala.collection.mutable.ListBuffer.empty[String]
    steps.foreach {
      case PathStep.Field(fieldName) =>
        currentType match
          case Type.Bundle(fields) =>
            currentType = fields.find(_._1 == fieldName).map(_._2).getOrElse(
              throw EmitterError(s"bundle has no field `$fieldName`"))
            name = s"${name}_$fieldName"
          case other => throw EmitterError(s"field `$fieldName` selected from non-bundle $other")
      case PathStep.Index(idx) =>
        currentType match
          case Type.Vec(_, elem) =>
            currentType = elem
            if ctx.isPort(id) then idx match
              case Expr.Lit(v, _, _) => name = s"${name}_${v.toInt}"
              case _ => throw EmitterError("runtime index on a port Vec is not supported")
            else arrayIndices += s"[${emitIndex(idx, ctx)}]"
          case _: Type.UInt | _: Type.SInt | _: Type.Bits | _: Type.GrayCode =>
            currentType = Type.Bool
            arrayIndices += s"[${emitIndex(idx, ctx)}]"
          case other => throw EmitterError(s"index selected from non-indexable $other")
      case PathStep.Slice(hi, lo) =>
        // R6.7 — the window, spelled the way `emitSelect` spells a read of the
        // same bits: a one-bit window is `x[7]`, never `x[7:7]`, so a
        // part-select target and a bit-select target of the same bit are the
        // same text (R12).
        currentType match
          case _: Type.UInt | _: Type.SInt | _: Type.Bits | _: Type.GrayCode | Type.Bool =>
            currentType = Type.UInt(hi - lo + 1)
            arrayIndices += (if hi == lo then s"[$hi]" else s"[$hi:$lo]")
          case other => throw EmitterError(s"part-select taken of non-bit-vector $other")
      case PathStep.VarSlice(lo, w) =>
        // R34 — the indexed part-select `[lo +: w]`, the same spelling
        // `emitExpr` uses for the read, so a target and a read of the same
        // window are the same text (R12).
        currentType match
          case _: Type.UInt | _: Type.SInt | _: Type.Bits | _: Type.GrayCode | Type.Bool =>
            currentType = Type.UInt(w)
            arrayIndices += s"[${emitIndex(lo, ctx)} +: $w]"
          case other => throw EmitterError(s"runtime part-select taken of non-bit-vector $other")
    }
    name + arrayIndices.mkString

  /** An index inside `[…]`. A constant renders as a bare decimal rather than a
    * sized literal: `instr[31]`, not `instr[32'd31]`. The two spellings mean
    * the same thing, and the emitter must pick one — R21.4's sign extension
    * and R21.5's concatenations select bits by position, so a slice and an
    * index of the same signal have to read alike (R12). A runtime index is an
    * expression and emits as one (R14.1). */
  private def emitIndex(idx: Expr, ctx: EmitCtx): String = idx match
    case Expr.Lit(v, _, _) => v.toString
    case other             => emitExpr(other, ctx)

end VerilogEmitter

/** Raised when the emitter hits an illegal construct (e.g. a runtime index on
  * a port Vec — R14.1). This is a late signal for a condition the validator
  * should catch earlier; the emitter is the last line of defence. */
final case class EmitterError(msg: String) extends RuntimeException(msg)

/** Per-module name + context lookup, built fresh from the immutable IR (no
  * mutation of the IR itself). Carries the port-name set (R14.1 port-vs-
  * internal split) so `emitIndexed` knows whether a `Vec` root is a port. */
private final class EmitCtx(names: Map[SignalId, String], ports: Set[SignalId],
                            types: Map[SignalId, Type], val moduleName: String = ""):
  def name(id: SignalId): String = names.getOrElse(id, s"sig${id.value}")
  def isPort(id: SignalId): Boolean = ports.contains(id)
  def typeOf(id: SignalId): Type = types.getOrElse(id, Type.Bool)

  /** R21.6 — the emitter's half of the shared typer. Emission is
    * type-directed: whether an operation wraps its operands in `$signed`, and
    * how wide a `resize` or a product has to make them, are answers only the
    * typer has. Before R21 this context could type a signal id and nothing
    * else, which is why signedness had no emission story (Appendix D
    * finding 7). */
  def typeOfExpr(e: Expr): Type = ExprType.typeOf(e, typeOf)
  def widthOfExpr(e: Expr): Int = typeOfExpr(e).bitWidth
  def isSigned(e: Expr): Boolean = ExprType.isSigned(e, typeOf)
